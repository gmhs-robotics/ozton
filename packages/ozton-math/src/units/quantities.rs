//! Named constructors for the uom SI quantity catalog.

macro_rules! quantity_macros {
    ($d:tt; $($module:ident :: $quantity:ident),+ $(,)?) => {
        $(
            #[doc = concat!("Creates a typed uom `", stringify!($quantity), "` from a value and a uom unit name.")]
            #[macro_export]
            macro_rules! $module {
                ($d value:literal $d unit:ident) => {
                    $crate::quantity!($module::$quantity, $d value, $d unit)
                };
                ($d value:expr, $d unit:ident $d(,)?) => {
                    $crate::quantity!($module::$quantity, $d value, $d unit)
                };
            }
            pub use $module;
        )+
    };
}

